function readServerProperties(): Record<string, string> {
  if (!fs.existsSync(propsPath)) return {};
  const content = fs.readFileSync(propsPath, 'utf8');
  const result: Record<string, string> = {};
  content.split('\n').forEach((line) => {
    line = line.trim();
    if (line && !line.startsWith('#') && line.includes('=')) {
      const parts = line.split('=');
      const key = parts[0].trim();
      const val = parts.slice(1).join('=').trim();
      result[key] = val;
    }
  });
  return result;
}

function writeServerProperties(props: Record<string, string>) {
  let lines: string[] = ['# Minecraft server properties', '# Updated via Hosting Panel'];
  for (const [k, v] of Object.entries(props)) {
    lines.push(`${k}=${v}`);
  }
  fs.writeFileSync(propsPath, lines.join('\n'), 'utf8');
}

