const worldUploadStorage = multer.diskStorage({
  destination: (req, file, cb) => cb(null, SERVER_DIR),
  filename: (req, file, cb) => cb(null, `world-upload-${Date.now()}.zip`),
});
const worldZipUpload = multer({ storage: worldUploadStorage });

function getActiveLevelName(): string {
  if (fs.existsSync(propsPath)) {
    const props = fs.readFileSync(propsPath, 'utf8');
    const match = props.match(/^level-name=(.*)$/m);
    if (match && match[1]) return match[1].trim();
  }
  return 'world';
}

app.get('/api/worlds', (req, res) => {
  try {
    const activeName = getActiveLevelName();
    
    // Default worlds ensure created
    ['world', 'world_nether', 'world_the_end'].forEach(wName => {
      const wPath = path.join(SERVER_DIR, wName);
      if (!fs.existsSync(wPath)) {
        fs.mkdirSync(wPath, { recursive: true });
      }
    });

    const worldsList: any[] = [];
    const refreshedItems = fs.readdirSync(SERVER_DIR, { withFileTypes: true });

    refreshedItems.forEach(item => {
      if (item.isDirectory() && item.name !== 'plugins' && item.name !== 'backups' && item.name !== 'logs') {
        const itemPath = path.join(SERVER_DIR, item.name);
        let size = 0;
        try {
          const files = fs.readdirSync(itemPath);
          files.forEach(f => {
            try {
              const st = fs.statSync(path.join(itemPath, f));
              size += st.size;
            } catch {}
          });
        } catch {}

        let dim = 'normal';
        if (item.name.endsWith('_nether')) dim = 'nether';
        else if (item.name.endsWith('_the_end')) dim = 'the_end';
        else if (item.name !== 'world') dim = 'custom';

        const stats = fs.statSync(itemPath);

        worldsList.push({
          folderName: item.name,
          displayName: item.name,
          isActive: item.name === activeName,
          sizeBytes: size,
          dimensionType: dim,
          updatedAt: stats.mtime.toISOString(),
        });
      }
    });

    res.json({ activeLevelName: activeName, worlds: worldsList });
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

app.post('/api/worlds/active', (req, res) => {
  try {
    const { folderName } = req.body;
    if (!folderName) return res.status(400).json({ error: 'Folder name required' });

    let props = '';
    if (fs.existsSync(propsPath)) {
      props = fs.readFileSync(propsPath, 'utf8');
    }

    if (props.includes('level-name=')) {
      props = props.replace(/^level-name=.*$/m, `level-name=${folderName}`);
    } else {
      props += `\nlevel-name=${folderName}`;
    }

    fs.writeFileSync(propsPath, props, 'utf8');
    addLog(`[WorldManager]: Set active server level-name to "${folderName}"`, 'info');
    res.json({ success: true, activeLevelName: folderName });
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

