app.post('/api/modrinth/install', async (req, res) => {
  try {
    const { projectId, fileUrl: providedUrl, filename: providedFilename } = req.body;
    
    if (!projectId && !providedUrl) {
      return res.status(400).json({ error: 'Missing projectId or fileUrl' });
    }

    let downloadUrl = providedUrl;
    let targetFilename = providedFilename;

    // If fileUrl not provided directly, fetch project version from Modrinth
    if (!downloadUrl) {
      const versionsUrl = `https://api.modrinth.com/v2/project/${projectId}/version`;
      const vRes = await fetch(versionsUrl, {
        headers: {
          'User-Agent': 'HostPanel-MinecraftServerManager/1.0 (contact@example.com)',
        },
      });

      if (!vRes.ok) {
        throw new Error('Failed to fetch versions for Modrinth project');
      }

      const versions = await vRes.json();
      if (!Array.isArray(versions) || versions.length === 0) {
        throw new Error('No downloadable versions found for this project');
      }

      const latestVersion = versions[0];
      const primaryFile = latestVersion.files?.find((f: any) => f.primary) || latestVersion.files?.[0];

      if (!primaryFile) {
        throw new Error('No valid file artifact found in latest version');
      }

      downloadUrl = primaryFile.url;
      targetFilename = primaryFile.filename || `${projectId}.jar`;
    }

    if (!targetFilename) {
      targetFilename = `${projectId}.jar`;
    }

    // Download the file directly into PLUGINS_DIR
    const fileRes = await fetch(downloadUrl, {
      headers: {
        'User-Agent': 'HostPanel-MinecraftServerManager/1.0 (contact@example.com)',
      },
    });

    if (!fileRes.ok) {
      throw new Error(`Failed to download file from Modrinth (${fileRes.status})`);
    }

    const arrayBuffer = await fileRes.arrayBuffer();
    const buffer = Buffer.from(arrayBuffer);
    const destinationPath = path.join(PLUGINS_DIR, targetFilename);

    fs.writeFileSync(destinationPath, buffer);
    addLog(`[Modrinth]: Downloaded & installed ${targetFilename} into plugins folder!`, 'info');

    res.json({
      success: true,
      filename: targetFilename,
      sizeBytes: buffer.length,
      message: `Successfully installed ${targetFilename} from Modrinth!`,
    });
  } catch (err: any) {
    addLog(`[Modrinth Error]: ${err.message}`, 'error');
    res.status(500).json({ error: err.message || 'Failed to install from Modrinth' });
  }
});

