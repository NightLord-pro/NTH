app.get('/api/files', (req, res) => {
  const subFolder = (req.query.path as string) || '';
  const targetDir = path.normalize(path.join(SERVER_DIR, subFolder));

  if (!targetDir.startsWith(SERVER_DIR) || !fs.existsSync(targetDir)) {
    return res.json({ files: [], currentPath: subFolder });
  }

  try {
    const items = fs.readdirSync(targetDir, { withFileTypes: true });
    const files = items.map((item) => {
      const itemPath = path.join(targetDir, item.name);
      let stats;
      try {
        stats = fs.statSync(itemPath);
      } catch {
        stats = { size: 0, mtime: new Date() };
      }

      return {
        name: item.name,
        path: path.relative(SERVER_DIR, itemPath).replace(/\\/g, '/'),
        isDirectory: item.isDirectory(),
        sizeBytes: stats.size,
        updatedAt: stats.mtime.toISOString(),
        extension: item.isDirectory() ? 'folder' : path.extname(item.name).replace('.', ''),
      };
    });

    res.json({ files, currentPath: subFolder });
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

